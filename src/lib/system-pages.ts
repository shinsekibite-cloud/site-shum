/** Slugs that power dedicated public routes and must stay in CMS. */
export const SYSTEM_PAGE_SLUGS = ['privacy', 'about', 'rules', 'terms'] as const;
export type SystemPageSlug = (typeof SYSTEM_PAGE_SLUGS)[number];

export function isSystemPageSlug(slug: string): slug is SystemPageSlug {
  return (SYSTEM_PAGE_SLUGS as readonly string[]).includes(slug);
}

/** Strip HTML for signed download / hash. */
export function htmlToPlainText(html: string) {
  return html
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/(p|div|h[1-6]|li|tr)>/gi, '\n')
    .replace(/<\/(ul|ol|table)>/gi, '\n')
    .replace(/<li[^>]*>/gi, '• ')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/\r\n/g, '\n')
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

