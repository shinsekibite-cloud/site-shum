/** Create missing system pages so admins always see Privacy / About editors. */
export async function ensureSystemPages() {
  if (isNextBuildPhase()) return;
  for (const seed of SEEDS) {
    const existing = await prisma.pageContent.findUnique({ where: { slug: seed.slug } });
    if (existing) continue;
    try {
      await prisma.pageContent.create({
        data: {
          slug: seed.slug,
          title: seed.title,
          content: seed.content,
          images: '',
          menuPosition: seed.menuPosition,
          template: seed.template,
          status: 'PUBLISHED',
          publishedAt: new Date(),
        },
      });
    } catch (e) {
      console.warn('ensureSystemPages', seed.slug, e);
    }
  }

  // Dedicated /contacts route — hide CMS duplicate from footer/header menus
  try {
    await prisma.pageContent.updateMany({
      where: { slug: 'contacts', menuPosition: { not: 'NONE' } },
      data: { menuPosition: 'NONE' },
    });
  } catch (e) {
    console.warn('ensureSystemPages contacts menu', e);
  }

  // Soft-upgrade legal text when older seeds miss RF-2026 sections
  try {
    const rules = await prisma.pageContent.findUnique({ where: { slug: 'rules' } });
    if (
      rules &&
      (!rules.content.includes('Редакция от 15.08.2026-members') ||
        !rules.content.includes('Конкурсы и вакансии') ||
        !rules.content.includes('Государственные сервисы') ||
        !rules.content.includes('Портфолио, награды и игры') ||
        rules.content.includes('YoungPortal'))
    ) {
      await prisma.pageContent.update({
        where: { slug: 'rules' },
        data: { content: DEFAULT_RULES_HTML },
      });
    }
    const privacy = await prisma.pageContent.findUnique({ where: { slug: 'privacy' } });
    if (
      privacy &&
      (!privacy.content.includes('Редакция от 15.08.2026-members (РКН)') ||
        !privacy.content.includes('Конкурсы (только после входа)') ||
        !privacy.content.includes('Вакансии (только после входа)') ||
        !privacy.content.includes('Локализация баз данных') ||
        privacy.content.includes('YoungPortal'))
    ) {
      await prisma.pageContent.update({
        where: { slug: 'privacy' },
        data: { content: DEFAULT_PRIVACY_HTML },
      });
    }
    const about = await prisma.pageContent.findUnique({ where: { slug: 'about' } });
    if (
      about &&
      (!about.content.includes('Куда сходить') ||
        !about.content.includes('Центр развития молодежи Сочи') ||
        !about.content.includes('about-hero-visual') ||
        about.content.includes('YoungPortal') ||
        !about.content.includes('личной галереи') ||
        !about.content.includes('Конкурсы и вакансии'))
    ) {
      await prisma.pageContent.update({
        where: { slug: 'about' },
        data: { content: DEFAULT_ABOUT_HTML, title: about.title || 'О нас', template: 'HERO' },
      });
    }
    const terms = await prisma.pageContent.findUnique({ where: { slug: 'terms' } });
    if (
      !terms ||
      !terms.content.includes('не является публичной офертой') ||
      !terms.content.includes('Редакция от 15.08.2026-members')
    ) {
      if (terms) {
        await prisma.pageContent.update({
          where: { slug: 'terms' },
          data: { content: DEFAULT_TERMS_HTML, title: 'Пользовательское соглашение', status: 'PUBLISHED' },
        });
      }
    }
  } catch (e) {
    console.warn('ensureSystemPages legal upgrade', e);
  }
}
