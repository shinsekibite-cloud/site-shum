export function filterFaqCategories(
  categories: FaqCategory[],
  modules: Partial<Record<ModuleFlagKey, boolean>> | null | undefined
): FaqCategory[] {
  if (!modules) return categories;
  return categories.filter((cat) => {
    if (!cat.moduleKeys?.length) return true;
    return cat.moduleKeys.some((key) => modules[key] !== false);
  });
}

export function searchFaqCategories(categories: FaqCategory[], query: string): FaqCategory[] {
  const q = query.trim().toLowerCase();
  if (!q) return categories;
  return categories
    .map((cat) => ({
      ...cat,
      items: cat.items.filter(
        (item) => item.q.toLowerCase().includes(q) || item.a.toLowerCase().includes(q)
      ),
    }))
    .filter((cat) => cat.items.length > 0);
}
